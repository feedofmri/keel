"""Render a RepairReport as Markdown (terminal summary and pull-request body)."""

from __future__ import annotations

from .diffutil import diff_stats
from .types import AUTO_MERGE, RepairReport

BADGE = {AUTO_MERGE: "🟢 **AUTO-MERGE**", "NEEDS REVIEW": "🟡 **NEEDS REVIEW**"}


def _pct(d: dict[str, bool]) -> str:
    return f"{sum(d.values())}/{len(d)}" if d else "–"


def candidates_table(report: RepairReport) -> str:
    rows = ["| Candidate | Model | Applies | Failing→pass | No regressions | Adversarial | Risk score |",
            "|---|---|---|---|---|---|---|"]
    sel = report.selected.candidate.candidate_id if report.selected else None
    for e in sorted(report.evaluations, key=lambda e: e.score):
        mark = " ⭐" if e.candidate.candidate_id == sel else ""
        rows.append(f"| `{e.candidate.candidate_id}`{mark} | {e.candidate.generator} | "
                    f"{'✅' if e.applied else '❌'} | {_pct(e.fail_to_pass)} | {_pct(e.pass_to_pass)} | "
                    f"{_pct(e.attack_results)} | {e.score:.3f} |")
    return "\n".join(rows)


def pr_body(report: RepairReport, summary: str = "") -> str:
    d = report.decision
    sel = report.selected
    lines = [f"## Keel: {BADGE.get(d.label, d.label)}", ""]
    if summary:
        lines += [summary, ""]
    lines += ["### Why", *[f"- {r}" for r in d.reasons], ""]
    lines += ["### Guarantee",
              f"{d.guarantee}" if d.guarantee else "_none_",
              "",
              f"Risk level α = **{d.alpha:.0%}**, method **{d.method.upper()}**, "
              f"threshold **{d.threshold:.3f}**, this patch's risk score **{d.score:.3f}**.",
              "",
              "<sub>Assumes this bug is exchangeable with the calibration bugs (same models, prompts and "
              "kind of repository). The guarantee is over bugs on average, not about this one patch. "
              "\"Correct\" means passing held-out tests.</sub>", ""]
    if sel:
        st = diff_stats(sel.candidate.diff)
        lines += ["### Selected patch",
                  f"`{sel.candidate.candidate_id}` from **{sel.candidate.generator}**: "
                  f"{st.files} file(s), +{st.added}/−{st.removed} lines.", ""]
    lines += ["### All candidates", candidates_table(report), "",
              f"Failing tests repaired: {', '.join(f'`{t}`' for t in report.task.failing_tests) or '–'}",
              "", f"Model cost for this run: ${report.total_cost_usd:.4f}", "",
              "---", "_Generated by [Keel](https://github.com/feedofmri/keel): Meta Muse models propose, "
              "conformal risk control decides._"]
    return "\n".join(lines)
